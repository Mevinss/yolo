@dataclass(frozen=True)
class CameraIntrinsics:
    """Параметры камеры. focal_px калибруется через tools/calibrate_focal.py."""

    focal_px: float
    width: int
    height: int
    hfov_deg: float = 60.0
    # высота камеры над землёй, м — нужна для ground-plane оценки расстояния
    height_above_ground_m: float = 1.35
    # наклон камеры вниз, градусы (положительный = смотрит вниз)
    pitch_deg: float = 10.0


@dataclass
class Frame:
    """Один кадр с камеры телефона.

    seq — номер кадра в записи. Он же становится Tick.seq и служит
    индексом в video.mp4 при разметке опасностей, поэтому должен
    приходить от источника, а не назначаться конвейером: при потере
    кадров собственный счётчик конвейера разошёлся бы с видео.
    """

    image: np.ndarray            # BGR, как отдаёт OpenCV
    ts: float                    # монотонное время получения, сек
    intrinsics: CameraIntrinsics
    seq: int = 0


class PoseSource(str, Enum):
    GPS = "gps"
    DEAD_RECKONING = "dead_reckoning"   # счисление пути по шагам/оптическому потоку
    FUSED = "fused"
    REPLAY = "replay"                   # из записанной прогулки


@dataclass
class Pose:
    """Где находится и куда смотрит пользователь.

    heading_deg — азимут ВЗГЛЯДА (камеры), не движения. 0 = север, по часовой.
    Это принципиально: маршрут задан в географических азимутах,
    а поле риска — в углах относительно камеры.

    heading_sigma_deg — неопределённость курса, и она важнее, чем
    неопределённость позиции. Ошибка позиции в 10 м смещает маршрут;
    ошибка курса в 20 градусов заставляет систему уверенно указывать
    не в тот проход. Телефон в руке качается на десятки градусов,
    а магнитометр врёт рядом с металлом, поэтому величина должна
    приходить от слоя io и учитываться слиянием.
    """

    lat: float
    lon: float
    heading_deg: float
    ts: float
    accuracy_m: float = 10.0
    heading_sigma_deg: float = 15.0
    speed_mps: float = 0.0
    source: PoseSource = PoseSource.GPS


