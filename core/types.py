class HealthFlag(str, Enum):
    """Виды деградации системы.

    Незрячий не может проверить, работает ли приложение: молчание
    системы неотличимо от «впереди чисто». Поэтому деградация должна
    объявляться, а не подразумеваться. Аид, отказывающий молча,
    опаснее отсутствия аида: он вытесняет собственную осторожность
    пользователя, ничего не давая взамен.
    """

    GPS_DEGRADED = "gps_degraded"                 # точность хуже порога
    GPS_LOST = "gps_lost"                         # позиции нет вовсе
    HEADING_UNRELIABLE = "heading_unreliable"     # компас врёт / телефон качается
    LOW_LIGHT = "low_light"                       # камера теряет полноту детекции
    CAMERA_STALLED = "camera_stalled"             # кадры перестали приходить
    DEPTH_UNAVAILABLE = "depth_unavailable"       # опасности без класса не видны
    HIGH_LATENCY = "high_latency"                 # реакция вне окна безопасности
    ROUTE_UNAVAILABLE = "route_unavailable"       # маршрут не построен
    OFF_ROUTE_NO_REPLAN = "off_route_no_replan"   # сошли и перестроить не удалось


@dataclass
class SystemHealth:
    """Состояние системы в данный момент.

    confidence — насколько системе можно доверять, 0..1. Используется
    guidance для смягчения формулировок: при низком значении вместо
    «свободно» произносится «препятствий не вижу, будьте осторожны».
    Разница существенна: первое утверждает факт о мире, второе —
    факт о системе.
    """

    flags: list = field(default_factory=list)     # list[HealthFlag]
    confidence: float = 1.0
    # с какого момента система деградировала — чтобы не молчать об этом
    # дольше некоторого срока и не повторять каждую секунду
    degraded_since_ts: Optional[float] = None
    # уточнение для озвучки, напр. «темно» или «нет спутников»
    detail: Optional[str] = None

    @property
    def degraded(self) -> bool:
        return bool(self.flags)


