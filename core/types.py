class DistanceSource(str, Enum):
    """Откуда взялась оценка расстояния — влияет на доверие к ней."""

    BBOX_HEIGHT = "bbox_height"     # по известной высоте класса объекта
    GROUND_PLANE = "ground_plane"   # по точке касания земли
    MONO_DEPTH = "mono_depth"       # MiDaS / Depth Anything
    FUSED = "fused"
    GEOMETRIC = "geometric"         # разрыв глубины без класса (яма, обрыв)
    UNKNOWN = "unknown"


@dataclass
class Detection:
    """Один обнаруженный объект.

    ТРЕКИНГ
    track_id связывает наблюдения одного объекта между кадрами.
    Из него выводится radial_velocity_mps — скорость сближения вдоль
    луча взгляда. Это меняет смысл предупреждения: стоящий человек
    в трёх метрах и идущий навстречу человек в трёх метрах требуют
    разной реакции, хотя выглядят одинаково на одном кадре.
    """

    label: str                        # класс модели, напр. "person"
    confidence: float                 # 0..1
    bbox: tuple                       # x1, y1, x2, y2 в пикселях
    # угол на центр объекта относительно оптической оси камеры, градусы:
    # отрицательный = слева, положительный = справа
    bearing_deg: float
    distance_m: Optional[float] = None
    distance_source: DistanceSource = DistanceSource.UNKNOWN
    # разброс оценки расстояния, м. None = неизвестен.
    # Нужен, чтобы guidance не произносил метры, которым нельзя верить.
    distance_sigma_m: Optional[float] = None
    track_id: Optional[int] = None
    # скорость сближения вдоль луча взгляда, м/с.
    # Положительная = приближается, отрицательная = удаляется.
    radial_velocity_mps: Optional[float] = None
    ts: float = 0.0

    @property
    def time_to_contact_s(self) -> Optional[float]:
        """Время до контакта, с. None, если объект не приближается.

        Не хранится в логе: выводится из distance_m и radial_velocity_mps,
        а дублирование производных величин в записях прогулок приводит
        к расхождениям при пересчёте.
        """
        if self.distance_m is None or not self.radial_velocity_mps:
            return None
        if self.radial_velocity_mps <= 0:
            return None
        return self.distance_m / self.radial_velocity_mps


