class ManeuverType(str, Enum):
    DEPART = "depart"
    STRAIGHT = "straight"
    TURN_LEFT = "turn_left"
    TURN_RIGHT = "turn_right"
    SLIGHT_LEFT = "slight_left"
    SLIGHT_RIGHT = "slight_right"
    CROSSING = "crossing"          # переход — особый случай, свой протокол
    STAIRS_UP = "stairs_up"
    STAIRS_DOWN = "stairs_down"
    ARRIVE = "arrive"


@dataclass
class Maneuver:
    type: ManeuverType
    lat: float
    lon: float
    # азимут, по которому надо двигаться ПОСЛЕ манёвра
    exit_bearing_deg: float
    distance_from_prev_m: float
    # человекочитаемое имя ориентира, если есть в OSM
    landmark: Optional[str] = None
    # теги доступности участка после манёвра (tactile_paving, kerb, ...)
    accessibility: dict = field(default_factory=dict)


@dataclass
class Route:
    maneuvers: list
    total_distance_m: float
    # суммарная «стоимость доступности» — не то же самое, что длина
    total_cost: float
    # полилиния [(lat, lon), ...] для отрисовки и для замера отклонения
    polyline: list = field(default_factory=list)
    # Состав маршрута по типам инфраструктуры, метры.
    #
    # ЗАЧЕМ ОТДЕЛЬНОЕ ПОЛЕ, А НЕ ПОДСЧЁТ ПО МАНЁВРАМ
    # Считать переходы по числу рёбер crossing нельзя: маршрут по середине
    # проезжей части не содержит таких рёбер вовсе, и потому выглядит
    # «безопаснее» тротуарного, хотя пешеход там пересекает поток
    # непрерывно. Честная метрика — доля длины по типам инфраструктуры.
    profile: dict = field(default_factory=dict)


@dataclass
class GlobalGuidance:
    """Что говорит глобальный уровень в данный момент времени."""

    # требуемый азимут движения, географический (0 = север)
    theta_route_deg: float
    next_maneuver: Optional[Maneuver]
    distance_to_maneuver_m: float
    # отклонение от полилинии маршрута, м
    cross_track_error_m: float
    off_route: bool = False
    arrived: bool = False


