@dataclass
class RiskField:
    """Дискретизация пространства перед человеком в полярную сетку.

    Сетка: n_sectors по углу (в пределах FOV) x n_bands по дальности.
    cells[i][j] — суммарный риск в секторе i, полосе дальности j; 0 = свободно.

    Именно эта структура — общий язык между зрением и планированием.
    Локальный планировщик не знает про YOLO; он знает только про риск.
    Наполнять её может любой источник: детектор, карта глубины,
    сегментация покрытия, ультразвуковой датчик.

    РАЗРЕШЕНИЕ СЕТКИ НЕ ФИКСИРОВАНО КОНТРАКТОМ
    sector_edges_deg и band_edges_m хранятся внутри объекта и пишутся
    в каждый лог, поэтому число секторов и полос можно менять даже
    после сбора данных — это параметр конфигурации, а не контракта.

    contributors: {"сектор,полоса": [индексы в Tick.detections]}.
    Хранятся ИНДЕКСЫ, а не сами объекты: иначе каждая детекция попадает
    в лог дважды, а словарь с кортежами в ключах не сериализуется в JSON.
    """

    cells: np.ndarray                 # shape (n_sectors, n_bands), float >= 0
    sector_edges_deg: np.ndarray      # shape (n_sectors + 1,), слева направо
    band_edges_m: np.ndarray          # shape (n_bands + 1,), от ближней к дальней
    ts: float = 0.0
    contributors: dict = field(default_factory=dict)

    @property
    def n_sectors(self) -> int:
        return int(self.cells.shape[0])

    @property
    def n_bands(self) -> int:
        return int(self.cells.shape[1])


