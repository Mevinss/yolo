class Lang(str, Enum):
    KK = "kk"
    RU = "ru"
    EN = "en"


@dataclass
class Utterance:
    """Одна реплика. Уже прошла арбитраж — её действительно надо произнести."""

    text: str
    lang: Lang
    urgency: Urgency
    ts: float
    # срок годности, сек. Просроченную реплику произносить вредно:
    # «впереди яма» через 4 секунды — это уже про другое место.
    ttl_s: float = 3.0
    # ключ дедупликации: не повторять то же самое, пока обстановка та же
    dedup_key: Optional[str] = None
    # короткий тактильный паттерн параллельно с речью (для шумной улицы)
    haptic: Optional[str] = None


