@dataclass
class Corridor:
    """Один свободный проход. Углы — относительно оптической оси камеры."""

    center_deg: float
    left_deg: float
    right_deg: float
    # расстояние до ближайшего препятствия по курсу этого коридора, м
    clearance_m: float
    # средний остаточный риск внутри коридора (0 = совершенно чисто)
    mean_risk: float = 0.0

    @property
    def width_deg(self) -> float:
        return self.right_deg - self.left_deg


@dataclass
class LocalGuidance:
    """Что говорит локальный уровень — в углах ОТНОСИТЕЛЬНО КАМЕРЫ.

    ПОЧЕМУ ЗДЕСЬ ПРОФИЛЬ, А НЕ ОДИН УГОЛ
    Функция стоимости слияния требует R(theta) для произвольного theta.
    Если передать только рекомендованный угол, слияние вынуждено
    интерполировать между ним и маршрутным курсом — и промежуточное
    направление может оказаться прямо в препятствии.

    Пример отказа при передаче одного угла:
        маршрут прямо (0 градусов), впереди забор от -15 до +15,
        свободны коридоры при -45 (широкий) и +25 (узкий).
        Локальный уровень отдаёт -45 как самый широкий,
        слияние ищет компромисс между -45 и 0 и выбирает около -25,
        то есть внутрь забора.

    Поэтому наружу отдаётся весь профиль риска по углу и список
    коридоров-кандидатов. Выбор между ними делает слияние, потому что
    выбор зависит от маршрута, о котором локальный уровень не знает.
    """

    # R(theta): риск как функция угла, уже свёрнутый по дальности
    risk_profile: np.ndarray          # shape (N,), значения 0..1
    profile_angles_deg: np.ndarray    # shape (N,), углы от оптической оси
    # свободные проходы, отсортированы по убыванию ширины
    corridors: list = field(default_factory=list)
    # рекомендация локального уровня (обычно центр самого широкого коридора)
    theta_free_deg: float = 0.0
    corridor_width_deg: float = 0.0
    # расстояние до ближайшего блокирующего объекта прямо по курсу, м
    clearance_m: float = float("inf")
    # объекты, из-за которых пришлось отклоняться — для объяснимой фразы
    blocking: list = field(default_factory=list)
    # True, если свободного коридора нет вообще — команда «стоп»
    blocked: bool = False


