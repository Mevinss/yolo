@dataclass
class Tick:
    """Полный срез одной итерации цикла. Пишется в JSONL при прогоне.

    Из последовательности Tick'ов eval/metrics.py считает ВСЕ метрики
    статьи, поэтому здесь должно храниться всё, что может понадобиться:
    переснимать прогулку ради забытого поля дорого, а иногда невозможно
    (та же улица в тех же условиях второй раз не повторяется).

    Кадр здесь НЕ хранится. Видео пишется отдельным файлом, а seq
    служит индексом в нём — это на порядок компактнее и позволяет
    пересматривать спорные моменты при разметке.

    Производные величины (время до контакта, доли, скорости речи)
    тоже не хранятся: они считаются из полей при анализе. Дублирование
    приводит к расхождениям между записанным и пересчитанным.
    """

    seq: int                                  # = Frame.seq, индекс кадра в видео
    ts: float
    pose: Pose
    health: SystemHealth
    detections: list
    risk: Optional[RiskField] = None
    global_guidance: Optional[GlobalGuidance] = None
