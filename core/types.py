class Action(str, Enum):
    STRAIGHT = "straight"
    BEAR_LEFT = "bear_left"        # взять левее, не сходя с маршрута
    BEAR_RIGHT = "bear_right"
    TURN_LEFT = "turn_left"        # манёвр маршрута
    TURN_RIGHT = "turn_right"
    STOP = "stop"                  # коридор перекрыт
    SLOW = "slow"                  # узкий коридор / низкая уверенность
    WAIT_CROSSING = "wait_crossing"
    ARRIVED = "arrived"


class CrossingPhase(str, Enum):
    """Фазы прохождения пешеходного перехода.

    Для зрячего переход — обычная точка маршрута. Для незрячего это
    самый опасный участок пути, и поведение системы на нём отличается
    от обычного движения: сначала предупреждение заранее, затем
    остановка у края, затем удержание курса на проезжей части, где
    отклонение опаснее всего.

    Фаза пишется в лог и даёт прямые метрики: время ожидания у края
    и отклонение от курса во время перехода.
    """

    APPROACHING = "approaching"    # переход впереди, предупреждаем заранее
    WAITING = "waiting"            # стоим у края, ждём сигнала или просвета
    CROSSING = "crossing"          # идём по проезжей части, курс критичен
    COMPLETED = "completed"        # вышли на противоположный тротуар


class Urgency(int, Enum):
    """Определяет право вытеснения в guidance/scheduler.py."""

    INFO = 0          # «до поворота 40 метров»
    NAVIGATION = 1    # «поверните направо»
    CAUTION = 2       # «возьмите левее», сообщения о деградации
    EMERGENCY = 3     # «стоп» — вытесняет всё, игнорирует бюджет речи


@dataclass
class FusionResult:
    """Согласованное решение: куда идти с учётом маршрута И препятствий."""

    action: Action
    # итоговый азимут движения, географический
    theta_star_deg: float
    urgency: Urgency
    # отклонение от маршрутного курса, которое мы сознательно допустили
    deviation_from_route_deg: float
    # почему отклонились — для объяснимой фразы и для логов эксперимента
    reason: Optional[str] = None
    # индексы в Tick.detections, а не объекты: не дублируем данные в логе
    cause_indices: list = field(default_factory=list)
    # True, если отклонение стало устойчивым и надо перестроить маршрут
    replan_needed: bool = False
    # фаза перехода, если сейчас идёт его прохождение
    crossing_phase: Optional[CrossingPhase] = None
    # разбивка стоимости по слагаемым — для анализа ablation в статье
    cost_breakdown: dict = field(default_factory=dict)


