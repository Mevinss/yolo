"""
Контракты между слоями системы.

ЕДИНСТВЕННЫЙ модуль, который импортируют все остальные слои.
Слои НЕ импортируют друг друга напрямую — только эти типы.
Это позволяет:
  * тестировать слой в изоляции (подставив фиктивные объекты);
  * прогонять записанные прогулки без камеры (eval/replay.py);
  * заменить реализацию слоя, не трогая соседей.

СОГЛАШЕНИЯ О ЕДИНИЦАХ
---------------------
Расстояния  — метры
Углы        — градусы
Время       — секунды; ts везде монотонное время, не календарное
Координаты  — WGS84, широта и долгота в градусах

Две системы отсчёта углов, их нельзя смешивать:
  * углы КАМЕРЫ      — от оптической оси, минус слева, плюс справа
  * АЗИМУТЫ          — географические, 0 = север, по часовой
Перевод выполняется в одном месте: FusionPolicy._to_geographic().

Поток данных:

    Frame + Pose
        |
        v
    [perception]  -> list[Detection]
        |
        v
    [risk]        -> RiskField
        |
        +----------------------+
        |                      |
        v                      v
    [local_planner]        [routing]
    -> LocalGuidance       -> GlobalGuidance
        |                      |
        +----------+-----------+
                   v
              [fusion]  -> FusionResult
                   |
                   v
              [guidance] -> Utterance
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Optional

import numpy as np

